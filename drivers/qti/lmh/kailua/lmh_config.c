/*
 * The LMH clock is left as the boot loader set it up; only the current
 * sensor clock is divided, by 2 on v1 silicon and by 3 from v2.
 */
void lmh_plat_clock_init(void)
{
	uint32_t div = 2U;
	uint32_t ver = chipinfo_get_chip_version();

	if ((ver != CHIPINFO_VERSION_UNKNOWN) && (ver < CHIPINFO_VERSION(2, 0))) {
		div = 1U;
	}

	mmio_write_32(APSS_CC_ISENSE_DIV_CDIVR, div);
}
